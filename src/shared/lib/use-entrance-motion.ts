"use client";

import { useEffect, useState } from "react";

/**
 * 이 앱이 클라이언트에서 **한 번이라도 커밋을 마쳤는가.**
 *
 * 모듈 스코프에 두는 이유: 하이드레이션 첫 커밋 이전에 마운트되는 모든 컴포넌트가
 * 같은 답(false)을 봐야 서버 HTML과 어긋나지 않는다. 그 뒤로 마운트되는 것은 전부
 * 사용자 행동(탭·이동)이나 데이터 도착의 결과라 등장 모션의 대상이다.
 */
let hydratedOnce = false;

/**
 * 하이드레이션이 끝났다고 표시한다 — **루트(`AppProviders`)가 한 번 부른다.**
 * ⚠ 소비자(`useEntranceMotion`)가 스스로 세우게 두면, 소비자가 하나도 없는 화면(`/posts`·
 *   `/profile`)을 하드 로드한 뒤 첫 클라이언트 이동에서 마운트되는 결과 블록이 전부 정적으로
 *   그려진다 — 플래그가 아직 `false`라서다. 모든 페이지가 지나는 루트가 세워야 빠지지 않는다.
 */
export function useMarkHydrated(): void {
  useEffect(() => {
    hydratedOnce = true;
  }, []);
}

/**
 * 지금 마운트되는 요소에 **등장 모션을 줘도 되는가.**
 *
 * 규약(styling.md·globals.css의 결과 모션 절): 등장 모션은 **늦게 도착하는 것**에만 건다 —
 * 투표 뒤에 열리는 집계, 이동으로 새로 그려지는 분포, 탭을 열어 나타나는 라인업. SSR로
 * 이미 그려진 HTML에는 걸지 않는다(첫 페인트를 300ms 늦추고 하이드레이션 전 HTML과
 * 카운트업 숫자가 어긋난다).
 *
 * 그래서 판정은 "이 컴포넌트가 하이드레이션 **이후에** 마운트됐는가"다.
 * - 하드 로드·크롤러: 서버 렌더와 하이드레이션 렌더 모두 `false` → 정적으로 그린다.
 * - 클라이언트 이동·투표 뒤 결과 도착: `true` → 막대가 자라고 숫자가 올라온다.
 *
 * ⚠ 값은 **마운트 시점에 한 번 고정**된다(`useState` 초기화). 그래야 하이드레이션 렌더가
 *   서버와 같은 값을 보고, 같은 인스턴스가 나중에 리렌더돼도 모션이 다시 시작되지 않는다.
 *   플래그를 세우는 쪽은 이 훅이 아니라 루트다(`useMarkHydrated`).
 * ⚠ 그래서 **요소 타입이 바뀌어 서브트리가 재마운트되면** 안 된다 — 재마운트된 `CountUp`은
 *   하이드레이션 뒤라 0에서 다시 굴러 화면이 100%→0%→100%로 튄다(분할 카드의 면이 세션
 *   복원 때 `div`→`button`으로 바뀌던 사고). 세션 상태로 갈리는 것은 속성(`disabled`)까지다.
 * ⚠ 뒤로가기로 목록에 돌아오면 그 화면의 결과 블록도 "다시 마운트"라 재생된다 — 320ms
 *   안쪽 블록 하나라 수용한다. 목록 전체에 스태거를 거는 것과는 다르다(그건 금지).
 */
export function useEntranceMotion(): boolean {
  const [play] = useState(() => hydratedOnce);
  return play;
}
