/**
 * 마크다운 원문 → 평문 요약. 순수 함수라 서버에서도 import할 수 있다("use client" 없음).
 *
 * 소비처가 둘이라 여기로 승격했다(중복 구현 금지 — reuse.md):
 *   - app/posts/[id]/page.tsx  : og:description(공유 프리뷰)
 *   - entities/post/api/mappers: 목록 카드의 발췌 2행
 * 두 곳이 서로 다른 변환기를 쓰면 같은 글의 요약이 화면과 공유 프리뷰에서 달라진다.
 *
 * ⚠ 말줄임(`clamp`)은 **여기 없다 → `@/shared/lib/text`.** 도메인을 모르는 순수 함수인데
 *   입축구 상세까지 쓰게 되어 소비처가 셋이 됐다("3번째 소비자가 생기면 shared로").
 *   ⚠ 서버 소비자가 있으므로 배럴이 아니라 **직접 경로**로 가져온다(shared/lib 배럴은
 *   "use client" 훅을 담고 있다).
 */
import { clamp } from "@/shared/lib/text";

/**
 * 마크다운 기호를 걷어내 한 줄 평문으로 만든다.
 * 렌더러를 돌리지 않는다 — 서버에서 react-markdown을 태울 이유가 없다.
 *
 * ⚠ 입력이 DB의 excerpt(= content의 앞 300자 프리픽스)면 중간에서 잘린 상태라
 *   짝이 맞지 않는 기호가 남을 수 있다. 그래서 강조 기호는 짝을 따지지 않고 전부 제거한다.
 */
/**
 * 본문 마크다운의 **이미지 한 장**을 잡는 패턴(소스 문자열).
 *
 * ⚠ **이 앱에는 같은 패턴의 사본이 넷 있고 전부 같아야 한다** — 여기(발췌·og:description),
 *   `features/admin-post`의 URL 추출, DB의 `admin_strip_post_images`, 그리고 `post.excerpt`
 *   생성식. 갈리면 화면이 보여준 목록과 실제로 지워지는 대상이 어긋나거나 본문에 잔여물이 남는다.
 *   JS 두 곳은 이 상수를 공유하고, SQL 두 곳은 같은 형태를 손으로 맞춘다(언어가 달라 공유가 없다).
 *
 * ⚠ **URL 안의 괄호를 한 겹 허용한다.** `([^)]*)`는 첫 `)`에서 멈추는데 본문은 자유 텍스트라
 *   `…/b(1).png` 같은 주소가 실제로 들어온다(위키미디어가 대표적). 잘린 캡처는 제거를 조용한
 *   no-op으로 만들거나 본문에 `.png)` 잔여물을 남긴다.
 * ⚠ **제목(title)을 URL에 붙이지 않는다.** `![](…webp "캡션")`에서 `…webp "캡션"`까지 캡처하면
 *   그 값이 경로 검사(`{uuid}/{파일}` 두 세그먼트)를 **통과해** 존재하지 않는 키를 지우려 든다 —
 *   본문에서는 사라지는데 공개 버킷의 파일은 남고 로그에도 흔적이 없다.
 * ⚠ **꺾쇠로 감싼 주소(`<…>`)도 받는다** — 그 형태만 공백이 든 주소를 쓸 수 있다.
 *   반대로 감싸지 않은 주소는 공백에서 끊는다: CommonMark가 그렇고, **렌더러가 이미지로
 *   그리지 않는 것을 우리만 이미지로 세면 판정이 갈린다.**
 *
 * 캡처는 둘이다 — `[1]`이 꺾쇠 안, `[2]`가 맨 주소. 호출부는 `m[1] ?? m[2]`로 읽는다.
 * ⚠ **`g` 플래그를 붙인 정규식 객체를 공유하지 않는다**(`lastIndex`가 호출부 사이에 샌다) →
 *   소스 문자열만 내보내고 각자 `new RegExp(..., "g")`로 만든다.
 */
export const IMAGE_MARKDOWN_SOURCE = String.raw`!\[[^\]]*\]\(\s*(?:<([^<>]*)>|((?:[^\s()]|\([^()]*\))*))(?:\s+(?:"[^"]*"|'[^']*'|\([^()]*\)))?\s*\)`;

const IMAGE_RE = new RegExp(IMAGE_MARKDOWN_SOURCE, "g");

export function toPlainSummary(markdown: string, max: number): string {
  const plain = markdown
    .replace(/```[\s\S]*?```/g, " ") // 펜스 코드블록
    .replace(/`([^`]*)`/g, "$1") // 인라인 코드
    .replace(IMAGE_RE, " ") // 이미지 — 패턴은 위 단일 소스가 갖는다
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // 링크는 텍스트만
    .replace(/^\s{0,3}>+\s?/gm, "") // 인용
    .replace(/^\s{0,3}#{1,6}\s+/gm, "") // 헤딩
    .replace(/^\s{0,3}([-*+]|\d+\.)\s+/gm, "") // 목록 마커
    .replace(/^\s{0,3}([-*_])\s*(\1\s*){2,}$/gm, " ") // 수평선
    // GFM 표: 구분 행(|---|:--:|)을 통째로 버리고 남은 셀 구분자는 공백으로.
    // 안 하면 목록 발췌에 `| 선수 | 잔여계약 | |---|---|`가 그대로 찍힌다(실측).
    .replace(/^\s{0,3}\|?[\s:|-]*\|[\s:|-]*$/gm, " ")
    .replace(/\|/g, " ")
    .replace(/[*_~]/g, "") // 강조 기호
    .replace(/\s+/g, " ");
  return clamp(plain, max);
}
